// Tarea 1: perímetro y área de un círculo
let radioCirculo = 5;
let perimetroCirculo = 2 * 3.1416 * radioCirculo;
let areaCirculo = 3.1416 * radioCirculo * radioCirculo;
console.log('El radio del círculo es: ' + radioCirculo);
console.log('El perímetro del círculo es: ' + perimetroCirculo.toFixed(2));
console.log('El área del círculo es: ' + areaCirculo.toFixed(2));